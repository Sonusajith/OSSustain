CREATE TABLE repositories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    github_id BIGINT NOT NULL UNIQUE CHECK (github_id > 0),
    full_name TEXT NOT NULL UNIQUE CHECK (position('/' in full_name) > 1),
    default_branch TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    stars_at_selection INTEGER NOT NULL CHECK (stars_at_selection >= 0),
    size_group TEXT NOT NULL CHECK (size_group IN ('small', 'medium', 'large')),
    primary_language TEXT,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    fork BOOLEAN NOT NULL DEFAULT FALSE,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    selected_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE cohorts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    selection_date DATE NOT NULL,
    config_hash CHAR(64) NOT NULL CHECK (config_hash ~ '^[0-9a-f]{64}$'),
    criteria JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE cohort_memberships (
    cohort_id BIGINT NOT NULL REFERENCES cohorts(id) ON DELETE CASCADE,
    repository_id BIGINT NOT NULL REFERENCES repositories(id) ON DELETE RESTRICT,
    stratum TEXT NOT NULL CHECK (stratum IN ('small', 'medium', 'large')),
    inclusion_notes TEXT NOT NULL,
    PRIMARY KEY (cohort_id, repository_id)
);

CREATE INDEX idx_cohort_memberships_repository_id
    ON cohort_memberships (repository_id);
